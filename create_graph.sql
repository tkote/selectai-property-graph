DROP PROPERTY GRAPH IF EXISTS RESIDENTS_GRAPH ;

CREATE PROPERTY GRAPH RESIDENTS_GRAPH
VERTEX TABLES (
    DEMO.RESIDENTS AS RESIDENT KEY (ID)
        LABEL RESIDENT
        PROPERTIES (ID, NAME),

    DEMO.RESIDENTS_SUB1 AS INCOME KEY (ID)
        LABEL INCOME
        PROPERTIES (ID, VALUE AS AMOUNT),

    DEMO.RESIDENTS_SUB2 AS EXPENSE KEY (ID)
        LABEL EXPENSE
        PROPERTIES (ID, VALUE AS AMOUNT),

    DEMO.RESIDENTS_SUB3 AS EXPENSE_DETAIL KEY (ID)
        LABEL EXPENSE_DETAIL
        PROPERTIES (ID, KIND, VALUE AS AMOUNT)
)
EDGE TABLES (
    DEMO.RESIDENTS_SUB1 AS HAS_INCOME KEY (ID)
        SOURCE KEY (ID) REFERENCES RESIDENT (ID)
        DESTINATION KEY (ID) REFERENCES INCOME (ID)
        LABEL HAS_INCOME
        NO PROPERTIES,

    DEMO.RESIDENTS_SUB2 AS HAS_EXPENSE KEY (ID)
        SOURCE KEY (ID) REFERENCES RESIDENT (ID)
        DESTINATION KEY (ID) REFERENCES EXPENSE (ID)
        LABEL HAS_EXPENSE
        NO PROPERTIES,

    DEMO.RESIDENTS_SUB3 AS HAS_DETAIL KEY (ID)
        SOURCE KEY (SUB_ID) REFERENCES EXPENSE (ID)
        DESTINATION KEY (ID) REFERENCES EXPENSE_DETAIL (ID)
        LABEL HAS_DETAIL
        NO PROPERTIES
);

EXIT;
